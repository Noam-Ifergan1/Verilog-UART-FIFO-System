module TX_ROM ( //הגדרת שם למודול
input wire clk, //כניסת אות שעון של המערכת
input wire rd, //כניסת בקרה(אם אחד קורא מהזיכרון) 
input wire [1:0] adrs, //כניסת הכתובת אלו 2 ביטים שאומרים מאיזה שורה לקרוא
output reg [7:0] dout //הנתון שיוצא החוצה 8 ביטים של המילה שיצאה
//alwaysכי הוא מקבל ערך בתוך בלוק ה regמוגדר כ
);
//הגדרת הזיכרון:יוצר מערך של 4 שורות של 8 ביטים
reg [7:0] rom_memory [0:3]; 

//קורא פעם אחת בתחילת הסימולציה הפעלה ראשונית וטעינה
initial begin //תחילת בלוק האתחול
    $readmemh("tx_data.txt", rom_memory); //פונקציה שקוראת קובץ טקסט בשם שרשום בפנים וטוענת את התוכן למערך
end //סיום בלוק האתחול

//בלוק מסונכרן שקורה בכל פעימת שעון 
always @(posedge clk) begin //נותן הוראה לעשות את מה שמופיע בבלוק בעת עליית שעון
     if (rd) begin //אז תעשה rd=1 אם 
        dout <= rom_memory[adrs]; //dout וקורא את מה שיש בפנים ומעתיק את התוכן אל rom_memory לוקח את המיקום של adrs בודק איזה מספר רשום
    end //סיום תנאי
end //סיום הבלוק

endmodule //סיום המודול