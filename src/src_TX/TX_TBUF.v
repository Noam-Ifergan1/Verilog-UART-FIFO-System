module TX_TBUF ( //הגדרת המודול
input wire clk, //הגדרת שעון מערכת
input wire tx_clr, //הגדרת משתני איפוס
input wire ld, //הגדרת אות טעינת מילה חדשה מהזיכרון
input wire shr, //הגדרת אות הזזת ביטים ימינה
input wire [7:0] din, //המילה השלמה שמגיעה מהזיכרון
output wire tx_data //קו יציאה שמוציא ביט אחד כל פעם
);

reg [7:0] tbuf_reg; //הגדרת משתנה פנימי של 8 ביטים שמשמש כאחסון זמני

//החיבור שמקשר את היציאה לביט הימני ביותר 
//הביט שיוצא החוצה הוא זה שמשודר
assign tx_data = tbuf_reg[0]; 

//בלוק שעובד בעליית שעון או כשיש איפוס
always @(posedge clk) begin 
    if (tx_clr) begin //אם לחצו על איפוס אז
         tbuf_reg <= 8'b0; //תאפס את כל האחסון הזמני לאפס
    end //סיום התנאי
    else if (ld) begin //שווה אחד אז טוענים נתון חדש ld אם 
         tbuf_reg <= din; //dinלוקחים את כל שמונת הביטים באחסון ומכניסים ל
    end //סיום התאי
        else if (shr) begin //שווה אחד מזיזים את הנתון ימינה shr אם 
//כדי להזיז ימינה שמים 0 בצד שמאל ולוקחים את הביטים מהמצב הקודם
//הביט שהיה הימני ביותר(במקום 0) נעלם
    tbuf_reg <= {1'b0, tbuf_reg[7:1]}; 
    end //סיום התנאי
end //סיום הבלוק

endmodule //סיום המודול