module TX_adrs_reg ( //הגדרת המודול
input wire clk, //הגדרת אות השעון
input wire tx_clr, //הגדרת אות איפוס (כשהוא אחד מאפס) 
input wire inc, //כניסת בקרה שאומרת האם לקדם את הכתובת ב1 
output reg [1:0] adrs //הכתובת הנוכחית שיוצאת לזיכרון
);
//בלוק שעובד בעליית שעון או כשיש איפוס
always @(posedge clk) begin //אם יש קפיצה בשעון או איפוס אז 
    if (tx_clr) begin //בודקים האם לחצו על איפוס
         adrs <= 2'b00; //אם כן מאפס את הכתובת ל-0 
    end //סיום התנאי
    else if (inc) begin //אם לא היה איפוס מפעילים אינקרמנט (מזיז באחד) 
		 adrs <= adrs + 1'b1; //מזיזים את הכתובת הנוכחית באחד 
    end //סיום התנאי
end //סיום הבלוק

endmodule //סיום המודול