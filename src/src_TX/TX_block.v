module TX_block ( //הגדרת המודול המסכם
    input wire clk,       //כניסת אות שעון ראשי שמגיע מבחוץ ואחראי על הפעלת כלל המערכת
    input wire tx_clr,    //כניסת אות איפוס כללי שמגיע מבחוץ ומאפס את כלל הבלוקים
    input wire fifo_full, //אם שווה אחד מודיע שהתור מלא וצריך לעצור FIFOכניסת אות מה
    output wire tx_data,  //חוט יציאה טורי FIFOמוציא ומשדר ביט אחד לתוך ה
    output wire wr_enable,//שמאשר כתיבה של הביט הנוכחי FIFOאות בקרה חוט יציאה ל
    output wire tx_finish //יציאות אות בקרה למערכת כולה - אם שווה 1 אז מודיע שסיימנו להעביר את כל 4 המילים
);

//הגדרת חיבורים פנימיים בתוך הבלוק הראשי המחברים את כל הבלוקים הפנימיים
    wire [1:0] internal_adrs; //חוט שמעביר את הכתובת הפנימית לזיכרון (2 ביטים)
    wire [7:0] internal_dout; //חוט שמעביר את המילה (8 ביט) מהזיכרון לאוגר הזזה
    wire ctrl_rd;  //חוט פקודה בגודל ביט לקריאה מהזיכרון - אם שווה ל1 אז אומר שקורא מהזיכרון
    wire ctrl_ld;  //חוט פקודה בגודל ביט לטעינה של האוגר הזזה - אם שווה ל1 אז אומר לטעון את האוגר הזזה 
    wire ctrl_shr; //חוט פקודה בגודל ביט להזזת הביטים ימינה - אם שווה ל1 אז מזיז ימינה
    wire ctrl_inc; //חוט פקודה בגודל ביט לקידום הכתובת למילה הבאה - אם שווה ל1 אז מזיז ב1

//חיבור ארבעת הבלוקים יחד

    //חיבור רגיסטר הכתובת (סופר מ0 עד 3) אל המערכת
    TX_adrs_reg u_TX_adrs_reg (
        .clk(clk),           //חיבור השעון הראשי אל השעון הפנימי
        .tx_clr(tx_clr),     //חיבור ריסט ראשי אל ריסט פנימי
        .inc(ctrl_inc),      //חיבור כניסת הפקודה שאומרת לקדם את המונה לקידום הפנימי
        .adrs(internal_adrs) //חיבור הכתובת הנוכחית לחוט פנימי
    );

    // חיבור זיכרון של TX אל המערכת
    TX_ROM u_TX_ROM (
        .clk(clk),             //חיבור השעון הראשי אל השעון הפנימי
        .rd(ctrl_rd),          //חיבור בקרת הקריאה אל יחידת קריאה פנימית
        .adrs(internal_adrs),  //חיבור כניסת כתובות של הזיכרון אל חוט הצגת מקום נוכחי מהמונה
        .dout(internal_dout)   //חיבור של ה8 ביטים שקראנו אל החוט מידע פנימי לזיכרון
    );

    //חיבור אוגר ההזזה (מפרק מילה לביטים בודדים) אל המערכת
    TX_TBUF u_TX_TBUF (
        .clk(clk),            //חיבור השעון הראשי אל השעון הפנימי של הרגיסטר הזזה
        .tx_clr(tx_clr),      //חיבור ריסט ראשי אל ריסט פנימי של הרגיסטר הזזה
        .ld(ctrl_ld),         //חיבור כניסת פקודת טעינת הנתונים של הרגיסטר ההזזה אל טעינה פנימית
        .shr(ctrl_shr),       //חיבור כניסת פקודת הזזת הביטים ימינה של הרגיסטר ההזזה אל חוט פנימי
        .din(internal_dout),  //חיבור כניסת מידע של הרגיסטר ההזזה (8 ביטים) אל חוט נתונים פנימי
        .tx_data(tx_data)     //מוציא את הביט הבודד (ביט 0) ישר לחוט יציאה של המערכת
    );

    //חיבור יחידת בקרה מרכזית אל המערכת (FSM - מכונת מצבים)
    TX_FSM u_TX_FSM (
        .clk(clk),               //חיבור השעון הראשי אל השעון הפנימי של מכונת המצבים
        .tx_clr(tx_clr),         //חיבור איפוס ראשי אל איפוס פנימי של המכונת מצבים
        .fifo_full(fifo_full),   //אל מכונת המצבים שתדע מתי לעצור FIFOחיבור חוט ה
        .adrs(internal_adrs),    //חיבור כניסת מעקב הכתובת של המכונה אל חוט הכתובת הפנימי כדי שתדע מתי הגיע לשורה 3
        .rd(ctrl_rd),            //חיבור מוצא פקודת הקריאה של המכונה אל חוט פנימי
        .ld(ctrl_ld),            //חיבור מוצא פקודת הטעינה של המכונה אל חוט פנימי המפעיל את הרגיסטר הזזה
        .shr(ctrl_shr),          //חיבור מוצא פקודת ההזזה של המכונה אל חוט פנימי המבצע הזזה של ביט ימינה ברגיסטר
        .inc(ctrl_inc),          //חיבור מוצא פקודת הקידום כתובת של המכונה אל חוט פנימי המבצע קידום כתובת ב1
        .wr_enable(wr_enable),   //לחוט פנימי FIFOחיבור פקודת כתיבה של ה
        .tx_finish(tx_finish)    //חיבור אות סיום של כל השידורים לחוט חיצוני של המערכת כולה
    );

endmodule //TX סיום מודול הראשי של