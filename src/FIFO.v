module FIFO ( //הגדרת המודול (ראשון נכנס ראשון יוצא)
    input wire clk, //אות שעון המערכת
    input wire reset, //FIFO-איפוס ה
    input wire wr_enable, //כניסת פקודת כתיבה -קולט ביט מהמשדר
    input wire rd_enable, //פקודת קריאה מהמקלט
    input wire din, //FIFO-כניסת הנתון הטורי-ביט בודד שנכנס לתוך ה
    output reg dout, //למקלט FIFO-יציאת הנתון הטורי-ביט בודד שיוצא מה
    output wire full, //חוט בקרה במאותת למשדר שהמקום מלא ולא לשלוח יותר ביטים
    output wire empty //חוט בקרה שמאותת למקלט שהמקום ריק אין כרגע מה לקרוא
);

reg memory [0:7]; //(שמונה שורות של ביט אחד) FIFO-הגדרת זיכרון פנימי של ה 

//הגדרת מצביעים לשורות בזיכרון
reg [2:0] wr_ptr; //הגדרת משתנה אוגר (3 ביטים) שאומר איפה נשמור את הביט הבא שייכנס
reg [2:0] rd_ptr; //הגדרת משתנה אוגר (3 ביטים) שאומר מאיפה נוציא את הביט שייקרא

reg [3:0] count; //(ארבע ביטים כדי שנוכל לספור מאפס עד שמונה) FIFOמונה שעוקב אחרי מספר הביטים שיש ב

//הגדרת הדגלים (מתעדכן אוטמוטי) 
assign empty = (count == 4'd0); //ריק FIFOכשהמונה שווה לאפס ה
assign full  = (count == 4'd8); //מלא FIFOכשהמונה שווה לשמונה ה


    always @(posedge clk) begin //בלוק שקורא בכל עליית שעון
        if (reset) begin //אם לחצו על איפוס אז
            wr_ptr <= 3'd0; //מאפסים מצביע כתיבה
            rd_ptr <= 3'd0; //מאפסים מצביע קריאה
            count  <= 4'd0; //מאפסים את המונה
            dout   <= 1'b0; //מאפסים את היציאה
        end 
        else begin //אם אין איפוס אז
            
			//טיפול בפעולת הכתיבה (ביט חדש) 
            if (wr_enable && !full) begin //אם קיבלנו פקודת כתיבה והתור לא מלא אז 
                memory[wr_ptr] <= din;   //שומרים את הביט בשורה הפנויה
                wr_ptr <= wr_ptr + 1'b1; //מקדמים את המצביע לשורה הבאה
            end //סיום תנאי הכתיבה

            //טיפול בפעולת קריאה (מוציא ביט החוצה) 
            if (rd_enable && !empty) begin //אם קיבלנו פקודת קריאה והתור לא ריק אז
                dout <= memory[rd_ptr]; //מעתיקים את הביט השמור בשורה שמצביע הקריאה מראה אל היציאה
                rd_ptr <= rd_ptr + 1'b1; //מקדמים את מצביע הקריאה
            end //סיום תנאי הקריאה

            //עדכון מונה הביטים בתור
            if ((wr_enable && !full) && (rd_enable && !empty)) begin //אם באותו הרגע נכנס ביט וגם יצא ביט אז
                count <= count; //הכמות הכוללת נשארת זהה לכן שומרים על הערך הקיים 
            end //סיום מצב ראשון
            else if (wr_enable && !full) begin //אם רק נכנס ביט חדש ולא יצא אף ביט אז
                count <= count + 1'b1; //מגדילים את המונה באחד
            end //סיום מצב שני
            else if (rd_enable && !empty) begin //אם רק קראנו והוצאנו ביט ולא נכנס שום ביט חדש אז
                count <= count - 1'b1; //מקטינים את המונה באחד
            end //סיום מצב שלישי
            
        end //סיום בלוק מצב עבודה
    end //סיום בלוק המרכזי

endmodule //סיום המודול

