`timescale 1ns / 1ps //הגדרת יחידת זמן לסימולציה

module tb_RX_block(); //הגדרת מודול סביבת הבדיקה
reg clk; //הגדרת משתנה שעון למערכת
reg rx_clr; //הגדרת משתנה לאות איפוס
    
reg tx_vld; //הגדרת משתנה לדמות אות התקפות שמגיע מהמשדר
reg tx_data; //הגדרת משתנה שדרכו נשדר את הביטים הטוריים למקלט

//הכל מוגדר כחוטים בגלל שאנחנו רק צופים בהם
wire rx_rdy; //הגדרת חוט למעקב אחרי אות המוכנות שהמקלט מוציא
wire rx_finish; //הגדרת חוט למעקב אחרי אות הסיום הכללי של המקלט
wire [7:0] rx_mem_dout; //RAM-חוט חלון הראווה לתצוגה בלבד שמראה את תוכן המילה הנוכחית בזיכרון ה

//משתני עזר ללולאות הבדיקה
integer i, j; //i-סופר איזה מילה שולחים (מ0-3) 
//j-סופר איזה ביט אנחנו שולחים בתוך המילה מ(0-7)
    
//מערך ששומר את 4 המילים שאנחנו (המשדר המדומה) נרצה לשלוח אליו
    reg [7:0] test_words [0:3];

    RX_block dut ( //עותק של הבלוק הראשי
        .clk(clk), //חיבור כניסת שעון פיזית של המודול למשתנה
        .rx_clr(rx_clr), //חיבור כניסת האיפוס פיזית של המודול למשתנה 
        .tx_vld(tx_vld), //חיבור אישור התקפות של המודול למשתנה
        .tx_data(tx_data), //חיבור קו הנתונים לכניסה הטורית של המקלט
        .rx_rdy(rx_rdy), //חיבור חוט הקריאה לפין המוכנות שהמקלט מוציא
        .rx_finish(rx_finish), //חיבור יציאת אות הסיום של המודול ליציאה של סביבת הבדיקה
        .rx_mem_dout(rx_mem_dout) //מחברים את חלון הראווה של של הזיכרון כדי שנוכל לראות מה נכתב שם 
    );

    always begin //התחלת לולאה אינסופית המפעילה את שעון סביבת הבדיקה
        #5 clk = ~clk; //הערך של השעון מתהפך 5 ננו שניות
    end //סיום בלוק יצירת שעון

    initial begin //t=0 התחלת בלוק הרצה באופן חד פעמי שמתחיל בזמן
//טעינת מילים לדוגמא אל תוך מערך הבדיקה	
        test_words[0] = 8'hA5; // 10100101
        test_words[1] = 8'h3C; // 00111100
        test_words[2] = 8'hFF; // 11111111
        test_words[3] = 8'h00; // 00000000

//מצב התחלתי
        clk = 0; //איפוס ערך השעון
        rx_clr = 1; //הדלקת כפתור איפוס לאתחול המערכת
        tx_vld = 0; //אין שידור אות התקפות נשאר אפס
        tx_data = 0; //קו הנתונים בהתחלה מקבל אפס

        $display("Start RX Simulation");

        #20 rx_clr = 0; //המתנה של 20 ננו שניות כאשר האיפוס לחוץ ואז עוזבים את כפתור האיפוס
        #20; //המתנה של עוד 20 ננו שניות כדי לוודא שהמערכת יציבה (IDLE) 

		//מתחילים לשדר את ארבעת המילים בעזרת לולאה (דימוי TX) 
        for (i = 0; i < 4; i = i + 1) begin 
            
	//יתריע שהוא מוכן RX-הסביבת בדיקה עוצרת ומחכה שה
	wait (rx_rdy == 1);
            
//המקלט מוכן, מחכים עליית שעון אחת כדי להיות מסונכרנים איתו
            @(posedge clk);
            
            $display("Transfers word number %d to RX", i);
            
            tx_vld = 1; //אות התקפות הופך לאחד ואומר למקלט שהוא מוכן לשידור
            
            for (j = 0; j < 8; j = j + 1) begin //לולאה פנימית שעוברת על 8 ביטים של המילה הנוכחית מביט אפס עד ביט שבע (LSB)
                tx_data = test_words[i][j]; //שמים ביט אחד על הקו הטורי שאנו רוצים לשדר עכשיו
                @(posedge clk); //מחכים לפעימת השעון כדי לקלוט את הביטים
            end //סיום הלולאה 
            
			//נשלחה מילה שלמה
            tx_vld = 0; //סיימנו לשלוח 8 ביטים, מורידים את אות התקפות 
            tx_data = 0; //איפוס קו נתונים לאפס
            
            #30; // נותנים למקלט זמן לכתוב את זה לזיכרון ולקדם כתובת
        end //סיום הלולאה החיצונית

        //המערכת מחכה שהמקלט יתריע על סיום כולל
        wait (rx_finish == 1);
        $display("RX finished all 4 words");
        
        #50; //המתנה של 50 ננו שניות כדי שיהיה אפשר לראות בצורה ברורה על מסך הגלים את הסיום 
        $stop; //פקודה שעוצרת את הסימולטור
    end //סיום הבלוק

endmodule //סיום המודול של סביבת הבדיקה