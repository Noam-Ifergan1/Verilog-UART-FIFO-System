`timescale 1ns / 1ps //הגדרת יחידת זמן לסימולציה

module tb_TX_block(); //הגדרת המודול

reg clk; //הגדרת משתנה לשעון
reg tx_clr; //הגדרת משתנה לאות איפוס (הדלקה וכיבוי במהלך הבדיקה) 
reg rx_rdy; //RX דימוי מקלט כי אין בפועל RX הגדרת משתנה עבור 

wire tx_data; //הגדרת אאוטפוט ליציאת נתונים טורית של המודול
wire tx_vld; //הגדרת אאוטפוט שמחובר ליציאה שאומרת לנו אם הנתונים תקפים
wire tx_finish; //הגדרת אאוטפוט שמתחבר ליציאת סיום השידור של המודול ומציג מתי הסתיים שידור כל המילים 

//הגדרת מספר שלם שיעזור לנו בלולאה לספור איזה מילה אנחנו משדרים עכשיו  
integer i;

TX_block dut ( //עותק של הבלוק הראשי
    .clk(clk), //חיבור כניסת השעון הפיזית של המודול למשתנה
    .tx_clr(tx_clr), //חיבור כניסת האיפוס הפיזית של המודול למשתנה
    .rx_rdy(rx_rdy), //חיבור כניסת הכפתור "המקלט מוכן" למשתנה
    .tx_data(tx_data),//חיבור יציאת הנתונים של המודול ליציאה של סביבת הבדיקה
    .tx_vld(tx_vld), //חיבור יציאת התקפות של המודול לציאה של סביבת הבדיקה
    .tx_finish(tx_finish) //חיבור יציאת אות הסיום של המודול ליציאה של סביבת הבדיקה
    );

always begin //התחלת לולאה אינסופית המפעילה את שעון סביבת הבדיקה
    #5 clk = ~clk; //הערך של השעון מתהפך כל חמש ננו שניות
end //סיום בלוק יצירת השעון

initial begin //t=0 התחלת בלוק הרצה באופן חד פעמי שמתחיל בזמן 
//הגדרת מצב התחלה
    clk = 0; //איפוס אות שעון 
    tx_clr = 1; //הדלקת כפתור איפוס לאיתחול המערכת
    rx_rdy = 0; //כי הוא לא מוכן לקבל נתונים RXהגדרת ערך 0 לאות ומכונות של ה
        
//נדפיס הודעה למסך שמתחילים
    $display("Start TX simulation");

//המתנה של 20 ננו שניות כאשר האיפוס לחוץ ואז עוזבים את כפתור האיפוס
    #20 tx_clr = 0;
        
//המתנה של עוד 20 ננו שניות כדי לוודא שהמערכת יציבה (IDLE)
    #20;

//מתחילים לשדר את 4 המילים בעזרת לולאה
	for (i = 0; i < 4; i = i + 1) begin

 //הדפסת הודעה למערכת שמעדכנת איזה מילה אנחנו מבקשים
$display("Requesting word number: %d", i);
            
//המקלט הדמיוני שאומר למשדר אני מוכן לקבל את המילה הבאה
    rx_rdy = 1;
            
//יתריע שהוא התחיל לשדר TX-הסביבת בדיקה עוצרת ומחכה שה
    wait (tx_vld == 1);
            
//ברגע שהשידור מתחיל המקלט הדמיוני מוריד את המוכנות שלו כדי לא לקבל עוד מילה נוספת ברצף
	rx_rdy = 0;
            
//יתריע שהוא סיים לשדר את 8 הביטים של המילה הנוכחית TX-הסביבת בדיקה עוצרת שוב והפעם מחכה שה
    wait (tx_vld == 0);

//הדפסת הודעה למסך שמאשרת שהמילה הנוכחית הסתיימה בהצלחה
$display("Word number %d finished successfully", i);
            
//עושים הפסקה קטנה של 30 ננו-שניות לפני שמבקשים את המילה הבאה
    #30;
end //i<4 סיום לולאה, נחזור להתחלה אם 

    wait (tx_finish == 1); //המקלט הדמיוני מחכה בפעם האחרונה לראות שהמשדר אומר שהוא סיים הכל-כל ארבעת המילים עברו
    $display("TX finished all 4 words"); //הדפסת הודעה למסך שכל ארבעת המילים עברו בהצלחה והמשדר סיים
        
//המתנה של 50 ננו שניות כדי שיהיה אפשר לראות בצורה ברורה על מסך הגלים את הסיום
    #50;
    $stop; //פקודה שעוצרת את הסימולטור
end //סיום הבלוק

endmodule //סיום המודול של סביבת הבדיקה


