`timescale 1ns / 1ps //הגדרת יחידת זמן לסימולציה

module tb_TOP_System(); //הגדרת מודול סביבת הבדיקה למערכת הכוללת

//הגדרת חוטים ורגיסטרים לבדיקה
reg clk; //הגדרת משתנה שעון למערכת
reg reset; //הגדרת משתנה לאות איפוס (משותף לכל המערכת)

//חוטים למעקב שלנו בסביבת הבדיקה
wire tx_finish; //מעקב אחרי אות סיום שמגיע מהמשדר
wire rx_finish; //מעקב אחרי אות סיום שמגיע מהמקלט
wire [7:0] rx_mem_dout; //חוט תצוגה לזיכרון של המקלט (לראות את הנתונים שהגיעו)

//חיבור המערכת הכוללת אל סביבת הבדיקה
    TOP_System dut ( //יצירת עותק של המערכת השלמה והמשולבת
        .clk(clk), //חיבור שעון
        .reset(reset), //חיבור איפוס ראשי
        .tx_finish(tx_finish), //חיבור חוט מעקב סיום משדר
        .rx_finish(rx_finish), //חיבור חוט מעקב סיום מקלט
        .rx_mem_dout(rx_mem_dout) //חיבור חוט התצוגה של הזיכרון
    );

    always begin //התחלת לולאה אינסופית המפעילה את שעון המערכת
        #5 clk = ~clk; //הערך של השעון מתהפך כל חמש ננו שניות
    end //סיום בלוק יצירת שעון

    initial begin //t=0 התחלת בלוק הרצה באופן חד פעמי שמתחיל בזמן
        
        //הגדרת מצב התחלה
        clk = 0; //איפוס שעון
        reset = 1; //הדלקת כפתור איפוס לאתחול המערכת כולה

        $display("Start Full System Simulation"); //הדפסה למסוף שמתחילים

        #20 reset = 0; //המתנה של 20 ננו שניות ואז עוזבים את כפתור האיפוס

		//וכותב לזיכרון FIFOלאחר מכן המקלט מושך מה FIFOהמערכת עובדת אוטומטית - המשדר קורא ומעביר ל
        $display("System is running"); //הדפסה למסוף שהמערכת רצה

        //המתנה עד שהמקלט יסיים לקלוט את כל 4 המילים
        wait (rx_finish == 1); 
        
        $display("All 4 words transferred completely through FIFO"); //הדפסת הודעת הצלחה 
        
        #50; //המתנה של 50 ננו שניות כדי לראות את הגלים בבירור במסך 
        $stop; //פקודה שעוצרת את הסימולטור לחלוטין
    end //סיום הבלוק

endmodule //סיום המודול של סביבת הבדיקה