`timescale 1ns / 1ps //הגדרת יחידת זמן לסימולציה

module tb_FIFO(); //הגדרת מודול סביבת הבדיקה

//הגדרת חוטים ורגיסטרים לבדיקה
reg clk; //הגדרת משתנה שעון למערכת
reg reset; //הגדרת משתנה לאות איפוס
reg wr_enable; //הגדרת משתנה פקודת כתיבה ל-FIFO
reg rd_enable; //הגדרת משתנה פקודת קריאה מה-FIFO
reg din; //הגדרת חוט נתונים בכניסה (ביט בודד)
    
wire dout; //הגדרת חוט נתונים ביציאה מה-FIFO
wire full; //הגדרת דגל שמסמן שה-FIFO מלא
wire empty; //הגדרת דגל שמסמן שה-FIFO ריק

integer i; //משתנה עזר ללולאות של התרחישים

//לסביבת בדיקה FIFOחיבור ה
    FIFO dut ( //FIFOסביבת בדיקה של ה
        .clk(clk), //חיבור שעון
        .reset(reset), //חיבור איפוס
        .wr_enable(wr_enable), //חיבור פקודת כתיבה
        .rd_enable(rd_enable), //חיבור פקודת קריאה
        .din(din), //חיבור נתון כניסה
        .dout(dout), //חיבור נתון יציאה
        .full(full), //חיבור דגל מלא
        .empty(empty) //חיבור דגל ריק
    );

    //יצירת שעון למערכת
    always #5 clk = ~clk; //הערך של השעון מתהפך כל חמש ננו שניות

    initial begin //t=0 התחלת בלוק הרצה באופן חד פעמי שמתחיל בזמן 
        
        //הגדרת מצב אתחול
        clk = 0; //איפוס שעון
        reset = 1; //הדלקת כפתור איפוס לאתחול
        wr_enable = 0; //ביטול פקודת כתיבה
        rd_enable = 0; //ביטול פקודת קריאה
        din = 0; //איפוס נתון כניסה
        
        #20 reset = 0; //המתנה של 20 ננו שניות ואז עוזבים את האיפוס
        #10; //המתנה לייצוב המערכת

        $display("Scenario 1: Normal Write and Read"); //הדפסה למסוף שמתחילים תרחיש 1
        
        //שלב א: כתיבת 8 ביטים ברצף
        for (i = 0; i < 8; i = i + 1) begin //לולאה שחוזרת 8 פעמים לכתיבה
            @(posedge clk); //המתנה לעליית שעון
            wr_enable = 1; //לקלוט נתון FIFOפקודת כתיבה אומרים ל
            din = ~din; //הכנסת ערך הפוך לביט הקודם (לשם הבדיקה)
        end //סיום לולאת כתיבה
        wr_enable = 0; //כיבוי פקודת הכתיבה כי סיימנו לדחוף 8 ביטים
        #10; //המתנה של 10 ננו שניות כדי לראות את הגלים באופן תקין 
        
        //שלב ב: קריאת 8 ביטים ברצף
        for (i = 0; i < 8; i = i + 1) begin //לולאה שחוזרת 8 פעמים לקריאה
            @(posedge clk); //המתנה לעליית שעון
            rd_enable = 1; //לקרוא נתון FIFOפקודת קריאה אומרים ל
        end //סיום לולאת קריאה
        rd_enable = 0; //(ריק FIFOסיום פקודת הקריאה (ה
        #20; //המתנה של 20 ננו שניות כדי לראות את הגלים באופן תקין


        $display("Scenario 2: Write when FIFO is FULL"); //הדפסה למסוף שמתחילים תרחיש 2
        
        //מילוי התור מחדש ב-8 ביטים
        for (i = 0; i < 8; i = i + 1) begin //לולאה למילוי התור עד הסוף
            @(posedge clk); //המתנה לעליית שעון
            wr_enable = 1; //מתן פקודת כתיבה
            din = 1; //הכנסת ערך קבוע
        end //סיום לולאת מילוי
        @(posedge clk); //המתנה לעליית שעון נוסף
        wr_enable = 0; //עצירת פקודת כתיבה
        
        //התור מלא - ננסה לדחוף ביט נוסף בכוח
        $display("Attempting to write another bit"); //הדפסת הודעת ניסיון דריסה
        @(posedge clk); //המתנה לעליית שעון
        wr_enable = 1; //מתן פקודת כתיבה לביט התשיעי
        din = 0; //ננסה להכניס 0
        @(posedge clk); //המתנה לעליית שעון
        wr_enable = 0; //מפסיקים לכתוב (במסך הגלים נראה שהמונה נשאר 8)
        #20; //המתנה להתייצבות

        $display("Scenario 3: Read when FIFO is EMPTY"); //הדפסה למסוף שמתחילים תרחיש 3
        
        //ריקון התור כולו מהתרחיש הקודם
        for (i = 0; i < 8; i = i + 1) begin //לולאה לריקון התור
            @(posedge clk); //המתנה לעליית שעון
            rd_enable = 1; //מתן פקודת קריאה
        end //סיום לולאת ריקון
        @(posedge clk); //המתנה לעליית שעון נוסף
        rd_enable = 0; //עצירת פקודת הקריאה
        
        //התור ריק - ננסה לקרוא ממנו בכוח
        $display("Attempting to read from empty FIFO"); //הדפסת הודעת ניסיון קריאה על ריק
        @(posedge clk); //המתנה לעליית שעון
        rd_enable = 1; //מבקשים נתון כשהתור ריק לגמרי
        @(posedge clk); //המתנה לעליית שעון
        rd_enable = 0; //מפסיקים לבקש (במסך הגלים נראה שהמונה נשאר 0)
        #20; //המתנה להתייצבות


        $display("Scenario 4: Read/Write at different rates"); //הדפסה למסוף תרחיש אחרון
        
        //נדמה מצב שבו כותבים 2 ביטים מהר, ואז קוראים 1 לאט
        for (i = 0; i < 4; i = i + 1) begin //לולאה שרצה 4 פעמים
            
            //כתיבת ביט ראשון
            @(posedge clk); //המתנה לעליית שעון
            wr_enable = 1; //מתן פקודת כתיבה
            rd_enable = 0; //ללא פקודת קריאה
            din = 1; //הכנסת ערך 1
            
            //כתיבת ביט שני
            @(posedge clk); //המתנה לעליית שעון
            wr_enable = 1; //מתן פקודת כתיבה
            rd_enable = 0; //ללא פקודת קריאה
            din = 0; //הכנסת ערך 0
            
            //קריאת ביט אחד בלבד (המקלט כביכול נח יותר)
            @(posedge clk); //המתנה לעליית שעון
            wr_enable = 0; //המשדר מפסיק לכתוב
            rd_enable = 1; //מתן פקודת קריאה למקלט
        end //(FIFOסיום לולאת קצבים שונים(בסוף הפעולה נשארו 4 ביטים ממתינים בתוך ה
        
        //עצירת כל הפעולות
        @(posedge clk); //המתנה לעליית שעון
        wr_enable = 0; //איפוס פקודת כתיבה
        rd_enable = 0; //איפוס פקודת קריאה

        $display("Simulation Finished"); //הדפסת הודעת סיום הבדיקות
        #50 $stop; //המתנה של 50 ננו שניות ואז פקודה שעוצרת את הסימולציה לחלוטין
    end //סיום בלוק ההרצה

endmodule //סיום המודול