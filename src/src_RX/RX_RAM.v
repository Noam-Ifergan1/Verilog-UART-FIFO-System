module RX_RAM ( //הגדרת מודול הזיכרון
    input wire clk, //כניסת אות שעון של המערכת
    input wire wr, //כניסת אות בקרת כתיבה (אם 1 - כותב ושומר את הנתון בזיכרון) 
    input wire [1:0] adrs, //כניסת הכתובת אלו 2 ביטים שאומרים באיזו שורה לכתוב
    input wire [7:0] din, //RBUF כניסת נתונים מקבילית שמגיעה מאוגר ההזזה 
	output wire [7:0] dout //יציאה שמאפשרת לנו לראות מה יש בזיכרון
);

//הגדרת הזיכרון: יוצר מערך של 4 שורות של 8 ביטים
reg [7:0] memory [0:3]; 

//הוצאת הנתון החוצה באופן רציף כדי שנוכל לראות מה יש בכתובת הנוכחית
assign dout = memory[adrs];
	
//בלוק מסונכרן שקורה בכל פעימת שעון 
    always @(posedge clk) begin //נותן הוראה לעשות את מה שמופיע בבלוק בעת עליית שעון
        if (wr) begin //(wr=1)אם התקבלה פקודת כתיבה אז
            memory[adrs] <= din; //לוקח את 8 הביטים שמחכים בכניסה ושומר אותם במערך בשורה שהכתובת מצביעה עליה
        end //סיום התנאי
    end //סיום הבלוק

endmodule //סיום המודול