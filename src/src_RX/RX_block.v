module RX_block ( //הגדרת המודול המסכם
input wire clk, //כניסת אות שעון ראשי שמגיע מבחוץ ואחראי על הפעל כלל המערכת
input wire rx_clr, //כניסת אות איפוס כללי שמגיע מבחוץ ומאפס את כלל הבלוקים
input wire fifo_empty, //שמודיע למקלט מתי התור ריק FIFOכניסת אות בקרה מה
input wire tx_data, //בכל קריאה FIFOכניסת נתונים טורית: ביט אחד שמגיע מה
output wire rd_enable, //להוציא ביט חדש FIFOאות בקרה-חוט יציאה שמבקש מה
output wire rx_finish, //יציאת אות בקרה למערכת כולה-אם שווה 1 אז מודיע שסיימנו להעביר את כל 4 המילים 
output wire [7:0] rx_mem_dout //יציאת תצוגה בלבד: מראה מה יש בכתובת הנוכחית בזיכרון
);

//הגדרת חיבורים פנימיים בתוך הבלוק הראשי מחברים את כל הבלוקים הפנימיים
wire [1:0] internal_adrs; //חוט המעביר את הכתובת (2 ביטים) ממונה הכתובות לזיכרון
wire [7:0] internal_din; //חוט המעביר מילה שלמה (8 ביטים) מאוגר ההזזה לזיכרון
wire ctrl_wr; //חוט פקודה בגודל ביט לכתיבה בזיכרון אם שווה ל-1 אומר שכותב
wire ctrl_shr; //חוט פקודה להזזת ביטים באוגר (קליטת ביט חדש)
wire ctrl_inc; //חוט פקודה בגודל ביט לקידום הכתובת למילה הבאה-אם שווה לאחד אז מזיז באחד

//חיבור רגיסטר הכתובת אל המערכת
    RX_adrs_reg u_RX_adrs_reg (
        .clk(clk), //חיבור השעון הראשי לשעון הפנימי
        .rx_clr(rx_clr), //חיבור ריסט ראשי לריסט הפנימי
        .inc(ctrl_inc), //חיבור כניסת הפקודה שאומרת לקדם את המונה לקידום פנימי
        .adrs(internal_adrs) //מוציא את הכתובת לחוט הפנימי
    );

//אל המערכת(מכיל 4 שורות ברוחב 8 ביטים) RX חיבור זיכרון של 
    RX_RAM u_RX_RAM (
        .clk(clk), //חיבור השעון הראשי אל השעון הפנימי
        .wr(ctrl_wr), //חיבור בקרת הכתיבה אל יחידת כתיבה פנימית
        .adrs(internal_adrs), //חיבור כניסת כתובות של הזיכרון אל חוט הצגת מקום נוכחי מהמונה
        .din(internal_din), //חיבור כניסת המידע של הזיכרון אל חוט המידע שמגיע מאוגר ההזזה
        .dout(rx_mem_dout) //מוציא נתונים החוצה רק לתצוגה במסך הגלים
    );

//חיבור אוגר ההזזה הקולט ביטים בודדים אל המערכת
    RX_RBUF u_RX_RBUF (
        .clk(clk), //חיבור השעון הראשי לשעון הפנימי
        .rx_clr(rx_clr), //חיבור ריסט ראשי לריסט הפנימי של אוגר ההזזה
        .shr(ctrl_shr), //פקודת הזזה/קליטה
        .tx_data(tx_data), //הכניסה הטורית שמגיעה ישירות מבחוץ
        .dout(internal_din) //מוציא מילה שלמה לחוט הפנימי שהולך לזיכרון
    );

//חיבור יחידת בקרה מרכזית אל המערכת (FSM-מכונת מצבים) 
    RX_FSM u_RX_FSM (
        .clk(clk), //חיבור השעון הראשי אל השעון הפנימי של מכונת מצבים 
        .rx_clr(rx_clr), //חיבור איפוס ראשי אל איפוס פנימי של מכונת המצבים
        .fifo_empty(fifo_empty), //אל מכונת המצבים FIFOחיבור חוט היציאה מה
        .adrs(internal_adrs), //חיבור כניסת מעקב הכתובות של המכונה אל חוט הכתובת הפנימי כדי שנדע מתי הגענו לשורה 3
        .wr(ctrl_wr), //שולח פקודת כתיבה לזיכרון
        .shr(ctrl_shr), //חיבור מוצא פקודת הזזה של המכונה אל חוט פנימי המבצע הזזה של ביט ימינה ברגיסטר
        .inc(ctrl_inc), //חיבור מוצא פקודת קידום הכתובת של המכונה אל חוט פנימי המבצע קידום לכתובת ב1
        .rd_enable(rd_enable), //חיבור חוט בקשת קריאה אל מכונת מצבים 
        .rx_finish(rx_finish) //שולח אות סיום החוצה
    );

endmodule //RX סיום המודול הראשי של