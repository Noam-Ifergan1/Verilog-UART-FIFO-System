module RX_RBUF ( //הגדרת המודול
    input wire clk, //הגדרת שעון מערכת
    input wire rx_clr, //הגדרת משתנה איפוס
    input wire shr, //הגדרת אות הזזת ביטים ימינה (לקלוט ביט חדש) 
    input wire tx_data, //קו כניסה טורי שמכניס ביט אחד כל פעם מהמשדר
    output wire [7:0] dout //יציאה שמוציאה את המילה השלמה (8 ביטים) לזיכרון
);

reg [7:0] rbuf_reg; //הגדרת משתנה פנימי של 8 ביטים שמשמש להרכבת המילה

//החיבור שמקשר את האחסון הפנימי ליציאה המקבילית
assign dout = rbuf_reg; 

//בלוק מסונכרן בעליית שעון
    always @(posedge clk) begin //מבצע את הוראות הבלוק בכל עליית שעון
        if (rx_clr) begin //אם לחצו על איפוס אז
            rbuf_reg <= 8'b0; //איפוס כל אוגר האחסון הזמני ל-0 
        end //סיום התנאי
        else if (shr) begin //אם התקבלה פקודת הזזה ימינה אז
			rbuf_reg <= {tx_data, rbuf_reg[7:1]}; //הביט החדש שנכנס מוכנס מצד שמאל וכל השאר זזים ימינה
//לאחר 8 פעמים הביט הראשון יגיע למקום הנכון בצד ימין			
        end //סיום התנאי
	end //סיום הבלוק

endmodule // סיום המודול